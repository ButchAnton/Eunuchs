#!/usr/bin/env python3
"""Generate the kernel symbol table (.ksyms section) from `nm -n` output.

usage: riscv64-elf-nm -n kernel.elf | gen_ksyms.py > ksyms.S
       gen_ksyms.py < /dev/null > ksyms.S        # empty table for pass 1
"""

import re
import sys

TEXT_TYPES = {"t", "T", "W"}
SKIP = re.compile(r"^(\.L|\$|__ksym)")


def main():
    by_addr = {}
    for line in sys.stdin:
        parts = line.split()
        if len(parts) != 3:
            continue
        addr, typ, name = parts
        if typ not in TEXT_TYPES or SKIP.match(name):
            continue
        a = int(addr, 16)
        # Aliases at one address: prefer real functions over linker markers
        # like __kernel_start (leading underscores), then globals.
        rank = (name.startswith("__"), typ == "t", name)
        if a not in by_addr or rank < by_addr[a][0]:
            by_addr[a] = (rank, name)
    syms = [(a, by_addr[a][1]) for a in sorted(by_addr)]

    out = sys.stdout
    out.write("/* Generated by tools/gen_ksyms.py; do not edit. */\n")
    out.write('    .section .ksyms, "a"\n    .balign 8\n')
    out.write("    .globl ksyms_num\nksyms_num:\n    .dword %d\n" % len(syms))
    out.write("    .globl ksyms_addrs\nksyms_addrs:\n")
    for a, _ in syms:
        out.write("    .dword 0x%x\n" % a)
    out.write("    .globl ksyms_offs\nksyms_offs:\n")
    off = 0
    for _, name in syms:
        out.write("    .word %d\n" % off)
        off += len(name) + 1
    out.write("    .globl ksyms_names\nksyms_names:\n")
    for _, name in syms:
        out.write('    .asciz "%s"\n' % name)


if __name__ == "__main__":
    main()
